import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Bot, Copy, Loader2, Save, Sparkles } from 'lucide-react';
import { useState } from 'react';
import { Link } from 'react-router';
import { toast } from 'sonner';
import type { z } from 'zod';
import type { aiBugAnalysisResponseSchema, aiPlaywrightResponseSchema, aiTestCasesResponseSchema } from '@qtm/shared';
import { Field, PageHeader, Panel } from '@/components/page';
import { ErrorState } from '@/components/states';
import { AiBadge, PriorityBadge, SeverityBadge } from '@/components/status-badge';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { NativeSelect } from '@/components/ui/native-select';
