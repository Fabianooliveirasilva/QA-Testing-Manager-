import type { AiStatus } from '@/lib/types';

interface AiEnvelope<T> {
  aiGenerated: true;
  provider: string;
  model: string;
  result: T;
}
type CasesResult = z.output<typeof aiTestCasesResponseSchema>;
type PlaywrightResult = z.output<typeof aiPlaywrightResponseSchema>;
type BugResult = z.output<typeof aiBugAnalysisResponseSchema>;

function Disclaimer({ model }: { model: string }) {
  return (
    <p className="flex items-center gap-2 text-xs text-muted-foreground">
      <AiBadge /> Generated by {model}. Review before use — AI output can be wrong and is never treated as an execution result.
    </p>
  );
}

export function AiPage() {
  const { organization } = useWorkspace();
  const status = useQuery({ queryKey: ['ai-status', organization.id], queryFn: () => api.get<AiStatus>(`/organizations/${organization.id}/ai/status`) });
  const s = status.data;
  const ready = s?.configured && s.enabledForOrganization;
  const readOnly = organization.role === 'VIEWER';

  return (
    <>
      <PageHeader title="AI Test Assistant" description="Draft test cases, Playwright automation and bug analyses for human review." />
      {status.error && <ErrorState error={status.error} onRetry={() => status.refetch()} />}
      {s && !s.configured && (
        <Panel className="mb-4">
          <p className="text-sm">
            <strong>Not configured.</strong> The server has no AI provider credentials. Set <code>AI_PROVIDER</code> and the provider API key (see <code>docs/AI.md</code>). No data
            is sent anywhere until then.
          </p>
        </Panel>
      )}
      {s?.configured && !s.enabledForOrganization && (
        <Panel className="mb-4">
          <p className="text-sm">
            <strong>Disabled for {organization.name}.</strong> Prompts you enter (requirements, bug descriptions) are sent to {s.provider} after automatic redaction of emails and secrets.{' '}
            {canManage(organization.role) ? (
              <Link to="/settings" className="text-primary hover:underline">
                Enable it in Settings
              </Link>
            ) : (
              'Ask an organization admin to enable it.'
            )}
          </p>
        </Panel>
      )}
      {s && ready && (
        <p className="mb-4 text-xs text-muted-foreground">
          {s.provider} · {s.model} · you: {s.usedToday}/{s.dailyLimit} today · organization: {s.organizationUsedToday}/{s.organizationDailyLimit} today
        </p>
      )}
      <Tabs defaultValue="cases">
        <TabsList>
          <TabsTrigger value="cases">Test cases</TabsTrigger>
          <TabsTrigger value="playwright">Playwright</TabsTrigger>
          <TabsTrigger value="bug">Bug analysis</TabsTrigger>
        </TabsList>
        <TabsContent value="cases">
          <GenerateCases disabled={!ready || readOnly} />
        </TabsContent>
        <TabsContent value="playwright">
          <GeneratePlaywright disabled={!ready || readOnly} />
        </TabsContent>
        <TabsContent value="bug">
          <AnalyzeBug disabled={!ready || readOnly} />
        </TabsContent>
      </Tabs>
    </>
  );
}

function useAiMutation<T>(path: string) {
  const { organization } = useWorkspace();
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: (body: unknown) => api.post<AiEnvelope<T>>(`/organizations/${organization.id}/ai/${path}`, body),
    onSettled: () => queryClient.invalidateQueries({ queryKey: ['ai-status', organization.id] }),
    onError: (e) => toast.error(errorMessage(e)),
  });
}

function GenerateCases({ disabled }: { disabled: boolean }) {
  const { organization, projectId: currentProject } = useWorkspace();
  const [requirement, setRequirement] = useState('');
  const [context, setContext] = useState('');
  const [selected, setSelected] = useState<number[]>([]);
  const [projectId, setProjectId] = useState(currentProject ?? '');
  const [suiteId, setSuiteId] = useState('');
  const projects = useProjects(organization.id);
  const suites = useSuites(projectId);
  const gen = useAiMutation<CasesResult>('test-cases');
  const queryClient = useQueryClient();

  const save = useMutation({
    mutationFn: async () => {
      const cases = gen.data?.result.testCases ?? [];
      const targetSuite = suiteId || suites.data?.[0]?.id;
      for (const i of selected) {
        const c = cases[i];
        if (!c || !targetSuite) continue;
        await api.post(`/projects/${projectId}/test-cases`, {
          suiteId: targetSuite,
          title: c.title,
          preconditions: c.preconditions,
          priority: c.priority,
          type: c.type,
          expectedResult: c.expectedResult,
          steps: c.steps,
          tags: [c.category.toLowerCase().replace('_', '-'), 'ai-generated'],
          status: 'DRAFT',
          aiGenerated: true,
        });
      }
      return selected.length;
    },
    onSuccess: (n) => {
      queryClient.invalidateQueries({ queryKey: ['test-cases', projectId] });
      toast.success(`${n} draft test case(s) saved for review`);
      setSelected([]);
    },
    onError: (e) => toast.error(errorMessage(e)),
  });

  const result = gen.data?.result.testCases;
  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <Panel title="Requirement">
        <form
          className="space-y-3"
          onSubmit={(e) => {
            e.preventDefault();
            setSelected([]);
            gen.mutate({ requirement, context });
          }}
        >
          <Field label="User story, requirement or acceptance criteria" htmlFor="ai-req">
            <Textarea id="ai-req" rows={8} value={requirement} onChange={(e) => setRequirement(e.target.value)} maxLength={8000} placeholder="As a customer I want to reset my password so that…" />
          </Field>
          <Field label="Additional context (optional)" htmlFor="ai-ctx">
            <Textarea id="ai-ctx" rows={3} value={context} onChange={(e) => setContext(e.target.value)} maxLength={4000} placeholder="Platform, business rules, constraints…" />
          </Field>
          <Button type="submit" disabled={disabled || !requirement.trim() || gen.isPending}>
            {gen.isPending ? <Loader2 className="animate-spin" /> : <Sparkles />} Generate test cases
          </Button>
        </form>
      </Panel>
      <Panel title="Suggestions">
        {!result ? (
          <p className="flex items-center gap-2 text-sm text-muted-foreground">
            <Bot className="size-4" /> Suggestions will appear here for review.
          </p>
        ) : (
          <div className="space-y-3">
            <Disclaimer model={gen.data?.model ?? ""} />
            <ul className="max-h-[28rem] space-y-2 overflow-y-auto">
              {result.map((c, i) => (
                <li key={i} className="rounded-lg border p-3 text-sm">
                  <label className="flex items-start gap-2">
                    <input
                      type="checkbox"
                      className="mt-1 accent-primary"
                      checked={selected.includes(i)}
                      onChange={() => setSelected((s) => (s.includes(i) ? s.filter((x) => x !== i) : [...s, i]))}
                    />
                    <span className="min-w-0">
                      <span className="font-medium">{c.title}</span>
                      <span className="mt-1 flex flex-wrap gap-1">
                        <PriorityBadge priority={c.priority} />
                        <span className="text-xs text-muted-foreground">
                          {humanize(c.category)} · {humanize(c.type)}
                        </span>
                      </span>
                      <ol className="mt-2 list-decimal space-y-0.5 pl-4 text-xs text-muted-foreground">
                        {c.steps.map((s, j) => (
                          <li key={j}>
                            {s.action}
                            {s.expectedResult && ` → ${s.expectedResult}`}
                          </li>
                        ))}
                      </ol>
                    </span>
                  </label>
                </li>
              ))}
            </ul>
            <div className="grid gap-2 sm:grid-cols-3">
              <NativeSelect aria-label="Target project" value={projectId} onChange={(e) => {
                setProjectId(e.target.value);
                setSuiteId('');
              }}>
                <option value="">Choose project…</option>
                {projects.data?.filter((p) => p.status === 'ACTIVE').map((p) => (
                  <option key={p.id} value={p.id}>
                    {p.name}
                  </option>
                ))}
              </NativeSelect>
              <NativeSelect aria-label="Target suite" value={suiteId} onChange={(e) => setSuiteId(e.target.value)} disabled={!projectId}>
                {suites.data?.map((s) => (
                  <option key={s.id} value={s.id}>
                    {s.name}
                  </option>
                ))}
              </NativeSelect>
              <Button disabled={!projectId || selected.length === 0 || save.isPending} onClick={() => save.mutate()}>
                <Save /> Save {selected.length || ''} as drafts
              </Button>
            </div>
          </div>
        )}
      </Panel>
    </div>
  );
}

function GeneratePlaywright({ disabled }: { disabled: boolean }) {
  const [scenario, setScenario] = useState('');
  const [baseUrl, setBaseUrl] = useState('');
  const [usePageObjects, setUsePageObjects] = useState(true);
  const gen = useAiMutation<PlaywrightResult>('playwright');
  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <Panel title="Scenario">
        <form
          className="space-y-3"
          onSubmit={(e) => {
            e.preventDefault();
            gen.mutate({ scenario, baseUrl: baseUrl.trim() || undefined, usePageObjects });
          }}
        >
          <Field label="Scenario or test case to automate" htmlFor="ai-scenario">
            <Textarea id="ai-scenario" rows={8} value={scenario} onChange={(e) => setScenario(e.target.value)} maxLength={8000} />
          </Field>
          <Field label="Base URL (optional)" htmlFor="ai-base">
            <Input id="ai-base" type="url" value={baseUrl} onChange={(e) => setBaseUrl(e.target.value)} placeholder="https://staging.example.com" />
          </Field>
          <label className="flex items-center gap-2 text-sm">
            <input type="checkbox" className="accent-primary" checked={usePageObjects} onChange={(e) => setUsePageObjects(e.target.checked)} /> Use Page Object Model
          </label>
          <Button type="submit" disabled={disabled || !scenario.trim() || gen.isPending}>
            {gen.isPending ? <Loader2 className="animate-spin" /> : <Sparkles />} Generate Playwright code
          </Button>
        </form>
      </Panel>
      <Panel title="Generated code">
        {!gen.data ? (
          <p className="text-sm text-muted-foreground">TypeScript files using @playwright/test will appear here.</p>
        ) : (
          <div className="space-y-3">
            <Disclaimer model={gen.data.model} />
            {gen.data.result.files.map((f) => (
              <div key={f.path}>
                <div className="mb-1 flex items-center justify-between">
                  <code className="text-xs">{f.path}</code>
                  <Button
                    size="sm"
                    variant="ghost"
                    onClick={() => navigator.clipboard.writeText(f.content).then(() => toast.success('Copied'), () => toast.error('Clipboard unavailable'))}
                  >
                    <Copy /> Copy
                  </Button>
                </div>
                <pre className="max-h-80 overflow-auto rounded-lg bg-muted p-3 text-xs">{f.content}</pre>
              </div>
            ))}
            {gen.data.result.notes && <p className="text-sm whitespace-pre-wrap text-muted-foreground">{gen.data.result.notes}</p>}
          </div>
        )}
      </Panel>
    </div>
  );
}

function AnalyzeBug({ disabled }: { disabled: boolean }) {
  const [description, setDescription] = useState('');
  const gen = useAiMutation<BugResult>('bug-analysis');
  const r = gen.data?.result;
  const list = (title: string, items: string[]) =>
    items.length > 0 && (
      <div>
        <h3 className="mb-1 text-xs font-semibold text-muted-foreground uppercase">{title}</h3>
        <ul className="list-disc space-y-1 pl-5 text-sm">
          {items.map((x, i) => (
            <li key={i}>{x}</li>
          ))}
        </ul>
      </div>
    );
  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <Panel title="Bug description">
        <form
          className="space-y-3"
          onSubmit={(e) => {
            e.preventDefault();
            gen.mutate({ description });
          }}
        >
          <Field label="What happened?" htmlFor="ai-bug">
            <Textarea id="ai-bug" rows={10} value={description} onChange={(e) => setDescription(e.target.value)} maxLength={8000} placeholder="Steps, expected vs actual behaviour, logs…" />
          </Field>
          <Button type="submit" disabled={disabled || !description.trim() || gen.isPending}>
            {gen.isPending ? <Loader2 className="animate-spin" /> : <Sparkles />} Analyze
          </Button>
        </form>
      </Panel>
      <Panel title="Analysis">
        {!r ? (
          <p className="text-sm text-muted-foreground">Possible causes, missing information and suggested severity will appear here.</p>
        ) : (
          <div className="space-y-4">
            <Disclaimer model={gen.data?.model ?? ""} />
            <div className="flex flex-wrap items-center gap-2 text-sm">
              Suggested: <SeverityBadge severity={r.suggestedSeverity} /> severity · <PriorityBadge priority={r.suggestedPriority} /> priority
            </div>
            <p className="text-sm text-muted-foreground">{r.rationale}</p>
            {list('Possible causes', r.possibleCauses)}
            {list('Missing information', r.missingInformation)}
            {list('Reproduction suggestions', r.reproductionSuggestions)}
          </div>
        )}
      </Panel>
    </div>
  );
}
